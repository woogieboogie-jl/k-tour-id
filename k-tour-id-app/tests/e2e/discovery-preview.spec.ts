test("preview: native Back/Forward and rotation preserve the selected stop", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.emulateMedia({ reducedMotion: "reduce" })
  await start(page)
  await page.getByRole("button", { name: "Cool", exact: true }).click()
  await page.getByRole("combobox", { name: "장소 종류", exact: true }).selectOption("food")
  const pin = page.locator("button[data-place-id='research-seoul-okdongsik']")
  await expect(pin).toBeVisible({ timeout: 20000 })
  await pin.click()
  await expect(page.locator("[data-place-card][data-selected=true]")).toHaveAttribute("data-place-card", "research-seoul-okdongsik")
  await page.mouse.move(220, 220)
  await page.mouse.down()
  await page.mouse.move(195, 242, { steps: 10 })
  await page.mouse.up()
  await expect.poll(() => page.evaluate(() => Boolean(window.history.state?.discoveryPreview?.snapshot?.camera))).toBe(true)
  // Wait for drag inertia before comparing the entire transform on native return.
  await page.waitForTimeout(600)
  const before = await pin.boundingBox()
  await page.goBack()
  await expect(page.getByTestId("discovery-preview")).toHaveAttribute("data-mode", "explore")
  await page.goForward()
  await expect(page.getByTestId("discovery-preview")).toHaveAttribute("data-mode", "cool")
  await expect(page.locator("[data-place-card][data-selected=true]")).toHaveAttribute("data-place-card", "research-seoul-okdongsik")
  await expect.poll(async () => {
    const after = await pin.boundingBox()
    return Math.abs(after!.x - before!.x) + Math.abs(after!.y - before!.y)
  }).toBeLessThan(2)
  await page.setViewportSize({ width: 844, height: 390 })
  await expect.poll(() => pin.evaluate(el => {
    const box = el.getBoundingClientRect()
    return el.contains(document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2))
  })).toBe(true)
  await page.getByRole("button", { name: "옥동식 · 장소 보기" }).click()
  await page.goBack()
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect(page.getByTestId("discovery-preview")).toHaveAttribute("data-mode", "cool")
})

