for (const size of [{ width: 320, height: 720 }, { width: 390, height: 844 }, { width: 430, height: 932 }, { width: 844, height: 390 }, { width: 1440, height: 1000 }]) {
  test(`preview: mobile composition / ${size.width}x${size.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(size)
    await start(page)
    await page.getByRole("button", { name: "Hot", exact: true }).click()
    await expect(page.locator("[data-place-card]")).toHaveCount(3)
    await expect(page.getByTestId("discovery-map")).toHaveAttribute("data-rendered", "true", { timeout: 20000 })
    await expect(page.locator("button[data-place-id]")).toHaveCount(3)
    const geometry = await page.evaluate(() => {
      const root = document.querySelector("main")!
      const header = root.querySelector("header")!.getBoundingClientRect()
      const tray = document.querySelector('[data-testid="discovery-tray"]')!.getBoundingClientRect()
      return { overflow: document.documentElement.scrollWidth - innerWidth, freeHeight: tray.top - header.bottom, freeWidth: innerWidth - tray.right, height: innerHeight, width: innerWidth }
    })
    expect(geometry.overflow).toBeLessThanOrEqual(1)
    if (size.width < 600) expect(geometry.freeHeight).toBeGreaterThanOrEqual(size.height * .5 - 2)
    else expect(geometry.freeWidth).toBeGreaterThanOrEqual(size.width * .5)
    await page.screenshot({ path: testInfo.outputPath("hot.png") })
    await page.getByRole("button", { name: /어니언 안국 · 장소 보기/ }).click()
    const dialog = page.getByRole("dialog")
    await expect(dialog.getByRole("button", { name: "지도에서 보기" })).toBeInViewport()
    const violations = (await new AxeBuilder({ page }).include('[data-testid="discovery-preview"]').analyze()).violations.filter(v => v.impact === "critical" || v.impact === "serious")
    expect(violations.map(v => `${v.id}: ${v.nodes.map(n => n.target).join(",")}`)).toEqual([])
    await page.screenshot({ path: testInfo.outputPath("place.png") })
  })
}

